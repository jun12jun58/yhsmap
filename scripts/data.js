function nameKey(tag, x, z) {
    return `${tag}|${x}|${z}`;
}

function uniqueName(base, used) {
    let name = base;
    let index = 2;
    while (used.has(name)) {
        name = `${base} ${index++}`;
    }
    used.add(name);
    return name;
}

export function parseLayoutText(text) {
    const floors = {};
    let current = null;
    for (const raw of text.split(/\r?\n/)) {
        const line = raw.trim();
        if (!line) continue;
        const floorMatch = line.match(/^(\d+)층$/);
        if (floorMatch) {
            current = Number(floorMatch[1]);
            floors[current] = { title: `${current}층`, blocks: [] };
            continue;
        }
        const tuple = line.match(/^\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)$/);
        if (!tuple || current == null) continue;
        const x = Number(tuple[1]);
        const z = Number(tuple[2]);
        const w = Number(tuple[3]);
        const d = Number(tuple[4]);
        const tag = Number(tuple[5]);
        floors[current].blocks.push({ x, z, w, d, tag, name: null });
    }
    Object.entries(floors).forEach(([floorKey, floor]) => {
        const floorNumber = Number(floorKey);
        const used = new Set();
        const table = NAME_TABLE[floorNumber] ?? {};
        floor.blocks.forEach((block, index) => {
            block.id = `${floorNumber}|${index}`;
            if (block.tag === TAG.ORIGIN) {
                block.name = '원점';
                return;
            }
            if (block.tag === TAG.CORRIDOR) {
                block.name = uniqueName('복도', used);
                return;
            }
            if (block.tag === TAG.STAIR) {
                block.name = uniqueName('계단', used);
                return;
            }
            const lookup = table[nameKey(block.tag, block.x, block.z)];
            const fallback = block.tag === TAG.TOILET ? '화장실' : '방';
            block.name = uniqueName(lookup || fallback, used);
        });
    });
    return floors;
}

export async function loadFloorsData() {
    try {
        const response = await fetch('./저장.txt');
        if (response.ok) return parseLayoutText(await response.text());
    } catch {
        // file:// or missing server: fall through
    }
    return parseLayoutText(EMBEDDED_LAYOUT);
}

export function getLayoutBounds(floorsData) {
    let minX = Infinity;
    let maxX = -Infinity;
    let minZ = Infinity;
    let maxZ = -Infinity;
    Object.values(floorsData).forEach(floor => {
        floor.blocks.forEach(block => {
            if (block.tag === TAG.ORIGIN) return;
            minX = Math.min(minX, block.x - block.w / 2);
            maxX = Math.max(maxX, block.x + block.w / 2);
            minZ = Math.min(minZ, block.z - block.d / 2);
            maxZ = Math.max(maxZ, block.z + block.d / 2);
        });
    });
    return {
        minX, maxX, minZ, maxZ,
        cx: (minX + maxX) / 2,
        cz: (minZ + maxZ) / 2,
        w: maxX - minX,
        d: maxZ - minZ
    };
}

export function getFloorNumbers(floorsData) {
    return Object.keys(floorsData).map(Number).sort((a, b) => a - b);
}

